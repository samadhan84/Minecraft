    val chars: List<Char> = glyphs.keys.toList()
    /** Atlas tiles used ("font_0" ...). */
    val TILES = (glyphs.size + 3) / 4

    /** Where [c] is: tile index (in font_N order) and cell 0..3, or null for spaces and unknown characters. */
    fun cell(c: Char): Int? = chars.indexOf(c.uppercaseChar()).takeIf { it >= 0 }

    /** The 5 x 7 pattern of glyph number [i] (rows of '#' and '.'). */
    fun rows(i: Int): Array<String> = glyphs.getValue(chars[i])
}
